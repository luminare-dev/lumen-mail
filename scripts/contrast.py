#!/usr/bin/env python3
"""Contrast table for the Lumen tokens (Python standard library only).

Reads src/less/lumen-tokens.less and src/less/contrast-pairs.json, then:
  * resolves every @lm-light-<role> and @lm-dark-<role> to a hex colour;
  * checks that every role in @lm-roles exists in both modes;
  * recomputes every derived colour written as "// mix(a NN%, b)" and checks its hex;
  * computes the WCAG 2.2 contrast ratio of every pair in light and dark mode;
  * writes docs/contrast.md (with --check: fails when that file is out of date);
  * exits 1 when a pair is below its minimum (4.5:1 text, 3:1 UI parts) or a value is wrong.

Optional: --kit PATH compares the brand colours with the kit's palette/tokens.json.

Usage: python3 scripts/contrast.py [--check] [--kit /root/important/brand]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "src" / "less" / "lumen-tokens.less"
PAIRS = ROOT / "src" / "less" / "contrast-pairs.json"
DOC = ROOT / "docs" / "contrast.md"

DECL_RE = re.compile(r"^@lm-([a-z0-9-]+)\s*:\s*([^;]+);[ \t]*(?://\s*(.*))?$", re.MULTILINE)
ROLES_RE = re.compile(r"^@lm-roles\s*:\s*([^;]+);", re.MULTILINE)
MIX_RE = re.compile(r"^mix\(([a-z0-9-]+)\s+(\d+)%,\s*([a-z0-9-]+)\)$")
HEX_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
REF_RE = re.compile(r"^@lm-([a-z0-9-]+)$")
MODES = ("light", "dark")


def declarations(text: str) -> dict[str, tuple[str, str | None]]:
    return {m.group(1): (m.group(2).strip(), (m.group(3) or "").strip() or None) for m in DECL_RE.finditer(text)}


def roles(text: str) -> list[str]:
    m = ROLES_RE.search(text)
    return [r.strip() for r in m.group(1).replace("\n", " ").split(",") if r.strip()] if m else []


def resolve(name: str, decls: dict[str, tuple[str, str | None]], seen: tuple[str, ...] = ()) -> str | None:
    if name in seen or name not in decls:
        return None
    value = decls[name][0]
    if HEX_RE.match(value):
        return value.upper()
    m = REF_RE.match(value)
    return resolve(m.group(1), decls, seen + (name,)) if m else None


def _channel(c: int) -> float:
    v = c / 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def luminance(hex_colour: str) -> float:
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _channel(r) + 0.7152 * _channel(g) + 0.0722 * _channel(b)


def ratio(a: str, b: str) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def mix(a: str, b: str, share: float) -> str:
    a, b = a.lstrip("#"), b.lstrip("#")
    return "#" + "".join(f"{round(int(a[i:i + 2], 16) * share + int(b[i:i + 2], 16) * (1 - share)):02X}"
                         for i in (0, 2, 4))


def analyse(text: str, pairs: list[dict]) -> tuple[list[dict], list[str]]:
    decls = declarations(text)
    problems: list[str] = []
    role_list = roles(text)
    if not role_list:
        problems.append("@lm-roles is missing or empty")
    for mode in MODES:
        for role in role_list:
            if f"{mode}-{role}" not in decls:
                problems.append(f"@lm-{mode}-{role} is missing (every role needs a light and a dark value)")
            elif resolve(f"{mode}-{role}", decls) is None:
                problems.append(f"@lm-{mode}-{role} does not resolve to a hex colour")
    for name, (value, comment) in decls.items():
        if not comment or not comment.startswith("mix("):
            continue
        m = MIX_RE.match(comment)
        if not m:
            problems.append(f"@lm-{name}: cannot read {comment!r}")
            continue
        a, b = resolve(m.group(1), decls), resolve(m.group(3), decls)
        if not a or not b:
            problems.append(f"@lm-{name}: unknown colour in {comment!r}")
            continue
        want = mix(a, b, int(m.group(2)) / 100)
        if value.upper() != want:
            problems.append(f"@lm-{name}: {value} is not {comment} = {want}")
    rows: list[dict] = []
    for pair in pairs:
        row = {"pair": pair}
        for mode in MODES:
            fg, bg = resolve(f"{mode}-{pair['fg']}", decls), resolve(f"{mode}-{pair['bg']}", decls)
            if not fg or not bg:
                problems.append(f"{mode}: cannot resolve {pair['fg']} or {pair['bg']}")
                row[mode] = None
                continue
            r = ratio(fg, bg)
            row[mode] = (r, fg, bg)
            if r < pair["min"]:
                problems.append(f"{mode}: {pair['fg']} on {pair['bg']} is {r:.2f}:1, needs {pair['min']}:1 ({pair['use']})")
        rows.append(row)
    return rows, problems


def render(rows: list[dict]) -> str:
    out = [
        "# Contrast",
        "",
        "Generated by `python3 scripts/contrast.py` from `src/less/lumen-tokens.less` and",
        "`src/less/contrast-pairs.json`; CI runs it with `--check`, so this table cannot drift from the",
        "tokens. Ratios follow WCAG 2.2: text needs 4.5:1 (SC 1.4.3), UI parts such as control borders,",
        "focus rings and indicators need 3:1 (SC 1.4.11). Light mode is Lumen's default; dark mode is",
        "Elastic's `html.dark-mode`. The task menu and the login hero are Night in both modes.",
        "",
        "| Foreground | Background | Use | Min | Light | Dark |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        p = row["pair"]
        cells = []
        for mode in MODES:
            v = row.get(mode)
            if v is None:
                cells.append("n/a")
                continue
            r, fg, bg = v
            mark = "pass" if r >= p["min"] else "FAIL"
            cells.append(f"{r:.2f}:1 {mark} (`{fg}` on `{bg}`)")
        out.append(f"| `{p['fg']}` | `{p['bg']}` | {p['use']} | {p['min']}:1 | {cells[0]} | {cells[1]} |")
    lowest = {mode: min((row[mode][0] for row in rows if row.get(mode)), default=0) for mode in MODES}
    out += ["", f"{len(rows)} pairs; lowest ratio {lowest['light']:.2f}:1 in light mode and "
                f"{lowest['dark']:.2f}:1 in dark mode.", ""]
    out += [
        "## Not covered by this table",
        "",
        "- Colours Elastic derives itself from our variables (for example the faded colour of deleted",
        "  messages) keep Elastic's formulas; they are not text Lumen sets.",
        "- The command palette has its own styles in a shadow root; its pairs use the same tokens.",
        "- Message bodies keep the sender's colours.",
        "",
    ]
    return "\n".join(out)


def check_kit(text: str, kit: Path) -> list[str]:
    data = json.loads((kit / "palette" / "tokens.json").read_text(encoding="utf-8"))
    decls = declarations(text)
    problems = []
    for name, entry in data.get("colors", {}).items():
        for key, suffix in (("hex", ""), ("bright", "-bright")):
            want = entry.get(key)
            ours = decls.get(name + suffix)
            if want and ours and ours[0].upper() != want.upper():
                problems.append(f"@lm-{name}{suffix} is {ours[0]}, the brand kit says {want}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/contrast.md is out of date")
    ap.add_argument("--kit", type=Path, help="brand kit root, to compare the brand colours")
    args = ap.parse_args(argv)
    text = TOKENS.read_text(encoding="utf-8")
    pairs = json.loads(PAIRS.read_text(encoding="utf-8"))["pairs"]
    rows, problems = analyse(text, pairs)
    if args.kit:
        problems += check_kit(text, args.kit)
    doc = render(rows)
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != doc:
            problems.append("docs/contrast.md is out of date: run python3 scripts/contrast.py")
    else:
        DOC.write_text(doc, encoding="utf-8")
    for p in problems:
        print(f"FAIL {p}")
    if problems:
        return 1
    print(f"ok: {len(rows)} pairs pass in light and dark mode")
    return 0


if __name__ == "__main__":
    sys.exit(main())
