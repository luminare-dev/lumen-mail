"""install-runtime: copy everything sync needs into one folder (default /opt/lumen-mail).

The sync unit runs from this copy, never from a git checkout, so a checkout can be moved, updated
or deleted without breaking the restore after a Roundcube update. Layout (the same as a checkout,
so Sources finds everything without options):

    <prefix>/bin/lumen-mail            wrapper: python3 -m lumen_mail with this generator
    <prefix>/generator/lumen_mail/     the Python package and compile.mjs
    <prefix>/src/less/                 our LESS sources
    <prefix>/skin/                     our static skin files
    <prefix>/palette/dist/lumen-palette.js   the prebuilt command palette (required): sync never runs Vite
    <prefix>/node_modules/             less, clean-css and their dependencies only
    <prefix>/version.txt, LICENSE, NOTICE, THIRD_PARTY_NOTICES.md, package.json
    <prefix>/RUNTIME.json              version, time and sha256 of every file

The new copy is assembled next to the prefix and swapped in with one atomic rename; the old copy
is removed afterwards. A folder that is not a lumen-mail runtime (no RUNTIME.json) is never
replaced without --force.
"""

from __future__ import annotations

import compileall
import datetime as _dt
import json
import os
import shlex
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from .fsops import exchange, remove_tree
from .log import Log
from .sources import LESS_FILES, PACKAGE_DIR, Sources
from .util import LumenError, sha256_file, walk_files

COMPILER_PACKAGES = ("less", "clean-css")
MANIFEST = "RUNTIME.json"
DEFAULT_PREFIX = Path("/opt/lumen-mail")
WRAPPER = """#!/bin/sh
# lumen-mail {version} runtime (generated by install-runtime; MIT, {url}).
# Runs the generator from this folder only: no git checkout, no current directory on sys.path.
export PYTHONPATH={generator}
export PYTHONDONTWRITEBYTECODE=1
export PYTHONSAFEPATH=1
export LUMEN_MAIL_PROG={prog}
exec {python} -m lumen_mail "$@"
"""


@dataclass
class RuntimeFile:
    source: Path
    rel: str
    mode: int = 0o644


def resolve_package(start: Path, name: str, top: Path) -> Path | None:
    """Node's lookup: <dir>/node_modules/<name> for <dir> = start and each parent up to top."""
    d = start
    while True:
        if d.name != "node_modules":
            candidate = d / "node_modules" / name
            if (candidate / "package.json").is_file():
                return candidate
        if d == top or d == d.parent:
            return None
        d = d.parent


def compiler_closure(node_modules: Path, roots: tuple[str, ...] = COMPILER_PACKAGES) -> list[Path]:
    """Package folders the compiler needs: the roots and their dependencies (optional ones only
    when installed), as found by Node's lookup from each package."""
    top = node_modules.parent
    seen: dict[Path, None] = {}
    queue: list[tuple[Path, str, bool]] = [(top, name, True) for name in roots]
    while queue:
        start, name, required = queue.pop(0)
        pkg = resolve_package(start, name, top)
        if pkg is None:
            if required:
                raise LumenError(f"the Node package {name!r} is missing below {node_modules}",
                                 ["run: npm ci --omit=dev --ignore-scripts --no-audit --no-fund"])
            continue
        pkg = pkg.resolve()
        if pkg in seen:
            continue
        seen[pkg] = None
        meta = json.loads((pkg / "package.json").read_text(encoding="utf-8"))
        for dep in sorted(meta.get("dependencies") or {}):
            queue.append((pkg, dep, True))
        for dep in sorted(meta.get("optionalDependencies") or {}):
            if dep not in (meta.get("dependencies") or {}):
                queue.append((pkg, dep, False))
    return sorted(seen, key=lambda p: p.as_posix())


def check_pins(sources: Sources) -> dict[str, str]:
    """The installed compiler versions must be the ones package.json pins."""
    pins = json.loads((sources.root / "package.json").read_text(encoding="utf-8")).get("dependencies", {})
    versions = {}
    for name in COMPILER_PACKAGES:
        meta_path = sources.node_modules / name / "package.json"
        if not meta_path.is_file():
            raise LumenError(f"{meta_path} is missing", ["run: npm ci --omit=dev --ignore-scripts --no-audit --no-fund"])
        version = json.loads(meta_path.read_text(encoding="utf-8")).get("version")
        if pins.get(name) and pins[name] != version:
            raise LumenError(f"node_modules has {name} {version}, package.json pins {pins[name]}",
                             ["run: npm ci --omit=dev --ignore-scripts --no-audit --no-fund"])
        versions[name] = version
    return versions


def runtime_files(sources: Sources) -> list[RuntimeFile]:
    sources.check()
    sources.require_palette()
    root = sources.root
    files: list[RuntimeFile] = []
    for name in ("version.txt", "LICENSE", "NOTICE", "THIRD_PARTY_NOTICES.md", "package.json"):
        files.append(RuntimeFile(root / name, name))
    for name in LESS_FILES:
        files.append(RuntimeFile(sources.less_dir / name, f"src/less/{name}"))
    for rel in walk_files(sources.skin_dir):
        files.append(RuntimeFile(sources.skin_dir / rel, f"skin/{rel.as_posix()}"))
    for path in sorted(PACKAGE_DIR.iterdir()):
        if path.is_file() and path.suffix in (".py", ".mjs"):
            files.append(RuntimeFile(path, f"generator/lumen_mail/{path.name}"))
    files.append(RuntimeFile(sources.palette, "palette/dist/lumen-palette.js"))
    for pkg in compiler_closure(sources.node_modules):
        rel_pkg = pkg.relative_to(sources.node_modules.resolve()).as_posix()
        for rel in walk_files(pkg):
            if rel.parts[0] == "node_modules":
                continue      # nested packages are listed by the closure themselves
            files.append(RuntimeFile(pkg / rel, f"node_modules/{rel_pkg}/{rel.as_posix()}"))
    return files


def install_runtime(sources: Sources, prefix: Path, log: Log, dry_run: bool = False, force: bool = False,
                    python: str | None = None, owner: tuple[int, int] | None = (0, 0)) -> int:
    prefix = prefix.absolute()
    versions = check_pins(sources)
    files = runtime_files(sources)
    total = sum(f.source.stat().st_size for f in files)
    if prefix.exists() and not (prefix / MANIFEST).is_file() and not force:
        raise LumenError(f"{prefix} exists and is not a lumen-mail runtime (no {MANIFEST}); refusing to replace it",
                         ["choose another --prefix, or pass --force"])
    python = python or ("/usr/bin/python3" if os.path.exists("/usr/bin/python3") else sys.executable)
    if dry_run:
        print(f"dry run: would install lumen-mail {sources.version} into {prefix}: {len(files)} files, "
              f"{total // 1024} KiB (less {versions['less']}, clean-css {versions['clean-css']}, "
              f"palette {sources.palette.stat().st_size} bytes), wrapper {prefix}/bin/lumen-mail using {python}")
        return 0
    prefix.parent.mkdir(parents=True, exist_ok=True)
    new = Path(tempfile.mkdtemp(prefix=f".{prefix.name}.new-", dir=prefix.parent))
    try:
        manifest_files = {}
        for f in files:
            dest = new / f.rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f.source, dest)
            manifest_files[f.rel] = sha256_file(dest)
        wrapper = new / "bin" / "lumen-mail"
        wrapper.parent.mkdir(parents=True, exist_ok=True)
        wrapper.write_text(WRAPPER.format(version=sources.version, url="https://github.com/luminare-dev/lumen-mail",
                                          generator=shlex.quote(str(prefix / "generator")),
                                          prog=shlex.quote(str(prefix / "bin" / "lumen-mail")),
                                          python=shlex.quote(python)), encoding="utf-8")
        manifest = {
            "lumen_version": sources.version,
            "installed_at": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
            "compiler": versions,
            "palette": True,
            "python": python,
            "files": manifest_files,
        }
        (new / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        # Bytecode now: the unit runs with a read-only file system and PYTHONDONTWRITEBYTECODE=1.
        compileall.compile_dir(str(new / "generator"), quiet=1, ddir=str(prefix / "generator"))
        for dirpath, _dirs, names in os.walk(new):
            os.chmod(dirpath, 0o755)
            if owner and os.geteuid() == 0:
                os.chown(dirpath, *owner)
            for name in names:
                path = os.path.join(dirpath, name)
                os.chmod(path, 0o644)
                if owner and os.geteuid() == 0:
                    os.chown(path, *owner)
        os.chmod(wrapper, 0o755)
        if prefix.exists():
            if exchange(new, prefix):
                remove_tree(new)
            else:
                old = prefix.with_name(f".{prefix.name}.old-{os.getpid()}")
                os.rename(prefix, old)
                os.rename(new, prefix)
                remove_tree(old)
        else:
            os.rename(new, prefix)
    except BaseException:
        remove_tree(new)
        raise
    log.notice(f"installed the lumen-mail {sources.version} runtime in {prefix} ({len(files)} files, "
               f"{total // 1024} KiB; less {versions['less']}, clean-css {versions['clean-css']}, "
               "command palette included)")
    print(f"Run it as: {prefix}/bin/lumen-mail <command> (for example: {prefix}/bin/lumen-mail status "
          "--roundcube /path/to/roundcube)")
    return 0
